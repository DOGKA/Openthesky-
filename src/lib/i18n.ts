export type StringKey = keyof (typeof STRINGS)["en"] | keyof (typeof STRINGS_2)["en"];
export type TFn = (key: StringKey, vars?: Record<string, string | number>) => string;

export function detectLocale(): SkyLocale {
  try {
    const tag = Intl.DateTimeFormat().resolvedOptions().locale || "en";
    const lang = tag.slice(0, 2).toLowerCase();
    if (lang === "tr" || lang === "de" || lang === "es") return lang;
  } catch {}
  return "en";
}

export function makeT(locale: SkyLocale): TFn {
  const table: Record<string, string> = {
    ...STRINGS.en,
    ...STRINGS_2.en,
    ...(STRINGS[locale] ?? {}),
    ...(STRINGS_2[locale] ?? {}),
  };
  return (key, vars) => {
    let s = table[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };
}

/** Locale tag for Intl formatting. */
export function localeTag(locale: SkyLocale): string {
  return { en: "en-US", tr: "tr-TR", de: "de-DE", es: "es-ES" }[locale];
}
